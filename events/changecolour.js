// hex colour code is of 6 alphanumerals following a '#'
// alphanumerals include "0123456789ABCDEF"

// generate a random colour 

const randomColour = function(){
    const hex = "0123456789ABCDEF"
    let colour = '#'
    for(let i=0 ; i<6 ; i++){
        let ind = Math.floor(Math.random() * 16)
        colour += hex[ind];
    }
    return colour;
}

