let startedChangingColour;

const startChnagingColour = function(){
    function changebgcolour(){
        document.body.style.backgroundColor = randomColour();
    }
    if(!startedChangingColour){ // only assign it if it is already null
        startedChangingColour = setInterval(changebgcolour, 1000);
    }
    // it prevents effect generated by clicking start button multiple times.
    // it only assigns it a new value when it is null, that is when stop button is clicked just before it.
}

document.querySelector('#start').addEventListener(
    'click',
    startChnagingColour
)

const stopChangingColour = function(){
    clearInterval(startedChangingColour);
    startedChangingColour = null; // very important
}

document.querySelector('#stop').addEventListener(
    'click',
    stopChangingColour
)